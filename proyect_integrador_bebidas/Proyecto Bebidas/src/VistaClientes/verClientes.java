    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String dni = tfDni.getText();
        
        IClienteDao CDao = new ClienteDaoImpl();
        Cliente cliente = CDao.buscarPorDNI(dni);
        
        if (cliente == null) {
            mostrarMensaje("Cliente no registrado");
            
        } else {
            this.idCliente = cliente.getIdcliente();
            lbDni.setText(cliente.getDni());
            lbName.setText(cliente.getNombre());
            lbLastname.setText(cliente.getApellido());
            lbEMail.setText(cliente.getEmail());
            lbTelf.setText(cliente.getTelefono());
            
        }
    }//GEN-LAST:event_btnBuscarActionPerformed


