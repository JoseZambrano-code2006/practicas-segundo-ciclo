    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int cantidadPedida = Integer.parseInt(txtCantidad.getText());
        int sotckDisponible = Integer.parseInt(mostrarStock.getText());
        
        if (cantidadPedida > sotckDisponible || cantidadPedida == sotckDisponible){
        JOptionPane.showMessageDialog(this,"No hay stock disponible");
            
        }else {
            String seleccionado = (String) comboBoxProductos.getSelectedItem();
            if (!seleccionado.equals("Seleccionar bebida")){
                String[] partes = seleccionado.split(" - ");
                int idBebida = Integer.parseInt(partes[0]); // Sacando el id
                    DetalleVentaImpl dvi = new DetalleVentaImpl();
                    DetalleVenta nuevoDetalleVenta = new DetalleVenta();
                    nuevoDetalleVenta.setIdProducto(idBebida);

                    int cantidad = Integer.parseInt(txtCantidad.getText().trim());
                    String precioTexto = mostrarPrecio.getText();
                    float precio = Float.parseFloat(precioTexto);

                    float precioTotal = precio * cantidad;

                    nuevoDetalleVenta.setCantidad(cantidad);
                    nuevoDetalleVenta.setSubtotal(precioTotal);
                    nuevoDetalleVenta.setIdVenta(1);

                    dvi.insert(nuevoDetalleVenta);

                    ProductoImpl productoImpl = new ProductoImpl();
                    productoImpl.reducir(cantidad, idBebida);



                    JOptionPane.showMessageDialog(this,"Venta realizado correctamente");

                    dispose();
                    Menu menu = new Menu();
                    menu.setVisible(true);
            }
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

