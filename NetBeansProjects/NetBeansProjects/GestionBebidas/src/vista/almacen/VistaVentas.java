    private void mostrarInfoBebida(int idBebida) {
        try {
            // Crear el controlador para manejar la lógica
            ProductoImpl productoImpl = new ProductoImpl();

            // Llamar al método read para obtener la bebida por su ID
            Producto producto = productoImpl.findById(idBebida);

        // Si la bebida no es nulo, mostrar sus detalles
        if (producto != null) {
            mostrarNombre.setText(producto.getCategoria());
            mostrarPrecio.setText("" + producto.getPrecio());
            mostrarStock.setText("" + producto.getCantidadDisponible());
        } else{
            // Si no se encuentra el zapato, limpiar los JTextField
            mostrarNombre.setText("");
            mostrarPrecio.setText("");
        }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error al obtener los detalles del zapato: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
