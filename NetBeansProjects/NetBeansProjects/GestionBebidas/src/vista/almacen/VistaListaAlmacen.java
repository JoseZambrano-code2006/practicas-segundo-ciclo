    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int filaSeleccionada = jTableAlmacen.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona un usuario para editar");
            return;
        }
        // Obtener el ID del usuario desde la primera columna de la fila seleccionada
        int productoId = (int) jTableAlmacen.getValueAt(filaSeleccionada, 0); // Columna 0 es el ID
        jTableAlmacen.setValueAt(txtCantidad.getText(), filaSeleccionada, 1); // Columna 1: Nombre
        int cantidadAumentada = Integer.parseInt(txtCantidad.getText());
        
        Producto productoEditado = new Producto();
        productoEditado.setIdBebida(productoId);
        productoEditado.setCantidadDisponible(cantidadAumentada);
        
        ProductoImpl productoImpl = new ProductoImpl();
        productoImpl.aumenta(productoId, cantidadAumentada);
        JOptionPane.showMessageDialog(this, "Aumentado correctamente");    
        txtCantidad.setText("");
        
        
    }//GEN-LAST:event_jButton3ActionPerformed
    private void cargarDatosTabla() {
            ProductoImpl productoImp = new ProductoImpl();
            List<Producto> productoLista = productoImp.listAll();

            // Limpiar la tabla
            modeloJTabla.setRowCount(0);

            // Agregar filas a la tabla
            for (Producto producto : productoLista) {
                Object[] row = {
                    producto.getIdBebida(),
                    producto.getCodigo(),
                    producto.getCategoria(),
                    producto.getMarca(),
                    producto.getTipo(),
                    producto.getTamaño(),
                    producto.getCantidadDisponible(),
                    producto.getPrecio(),
                    producto.getEstado()
                };
                modeloJTabla.addRow(row);
            }
        }
