    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
     if (jTableAlmacen.getRowCount() > 0) { //tabla no vacia
            if (jTableAlmacen.getSelectedRow() != -1) {
                int idProducto = Integer.parseInt(jTableAlmacen.getValueAt(jTableAlmacen.getSelectedRow(), 0).toString());
                
                
                int resp = JOptionPane.showConfirmDialog(null, "Esta usted seguro de eliminar el usuario?");
                if (JOptionPane.OK_OPTION == resp) {
                    ProductoImpl pi = new ProductoImpl();
                    pi.delete(idProducto);
                    JOptionPane.showMessageDialog(null, "Producto eliminado :( ", "INFORMATION_MESSAGE", JOptionPane.INFORMATION_MESSAGE);
                    cargarDatosTabla();
                } else {
                    JOptionPane.showMessageDialog(null, "Operación Cancelada :(", "INFORMATION_MESSAGE", JOptionPane.INFORMATION_MESSAGE);
                }
            }
        }
    }//GEN-LAST:event_jButton4ActionPerformed

