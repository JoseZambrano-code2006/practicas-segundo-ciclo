    private void cargarDatosTabla() {
        DetalleVentaImpl detalleVentaControl = new DetalleVentaImpl();
        List<DetalleVenta> detalleordenList = detalleVentaControl.listAll();

        // Limpiar la tabla
        modeloTablaVentas.setRowCount(0);

        // Agregar filas a la tabla
        for (DetalleVenta detalleVenta : detalleordenList) {
            Object[] row = {
                detalleVenta.getIdDetalleVenta(),
                detalleVenta.getNombreProducto(),
                detalleVenta.getCantidad(),
                detalleVenta.getSubtotal()
            };
            modeloTablaVentas.addRow(row);
        }
    }
